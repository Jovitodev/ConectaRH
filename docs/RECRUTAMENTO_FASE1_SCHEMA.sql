-- Fase 1: estruturas operacionais novas; sem importação dos dados demonstrativos.
create table public.empresas (
  id bigint generated by default as identity primary key,
  nome text not null unique,
  ativa boolean not null default true,
  cadastrada_por uuid references auth.users(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.vagas (
  id bigint generated by default as identity primary key,
  codigo text generated always as ('VAG-' || lpad(id::text, 6, '0')) stored unique,
  empresa_id bigint not null references public.empresas(id),
  responsavel_auth_user_id uuid not null references auth.users(id),
  titulo text not null,
  departamento text,
  descricao text,
  cidade_id integer references public.cidades(id),
  estado_id integer references public.estados(id),
  localidade_texto text,
  modalidade text,
  contrato text,
  salario_min numeric(12,2),
  salario_max numeric(12,2),
  requisitos text[] not null default '{}',
  beneficios text[] not null default '{}',
  areas text[] not null default '{}',
  etapas_iniciais text[] not null default '{}',
  visibilidade text not null default 'publica' check (visibilidade in ('publica','interna','sigilosa')),
  status text not null default 'rascunho' check (status in ('rascunho','ativa','pausada','encerrada')),
  inscricoes_inicio date,
  inscricoes_fim date,
  publicada_em timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint vagas_cidade_estado_check check (cidade_id is null or estado_id is not null),
  constraint vagas_salario_check check (salario_min is null or salario_max is null or salario_min <= salario_max),
  constraint vagas_inscricoes_check check (inscricoes_inicio is null or inscricoes_fim is null or inscricoes_inicio <= inscricoes_fim),
  constraint vagas_cidade_estado_fk foreign key (cidade_id, estado_id) references public.cidades(id, estado_id)
);

create index vagas_responsavel_status_idx on public.vagas(responsavel_auth_user_id,status,publicada_em desc);
create index vagas_publicadas_idx on public.vagas(publicada_em desc) where status='ativa' and visibilidade='publica';
create index vagas_empresa_idx on public.vagas(empresa_id);

alter table public.candidatos add constraint candidatos_id_usuario_unique unique (id,usuario_id);

create table public.candidaturas (
  id bigint generated by default as identity primary key,
  vaga_id bigint not null references public.vagas(id),
  candidato_id bigint not null,
  usuario_id bigint not null,
  candidato_auth_user_id uuid not null references auth.users(id),
  -- Retrato limitado ao que o candidato envia para este processo.
  nome_candidato text not null,
  email_candidato text not null,
  cidade_candidato text,
  estado_candidato text,
  escolaridade text,
  experiencias_resumo jsonb not null default '[]'::jsonb,
  habilidades text[] not null default '{}',
  idiomas_resumo jsonb not null default '[]'::jsonb,
  areas text[] not null default '{}',
  etapa_atual text not null default 'Triagem curricular',
  status text not null default 'em_andamento' check (status in ('em_andamento','aprovado','reprovado','contratado','desistiu')),
  aplicada_em timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint candidaturas_candidato_usuario_fk foreign key (candidato_id,usuario_id) references public.candidatos(id,usuario_id),
  constraint candidaturas_vaga_candidato_unique unique (vaga_id,candidato_id)
);

create index candidaturas_vaga_aplicada_idx on public.candidaturas(vaga_id,aplicada_em desc);
create index candidaturas_candidato_auth_idx on public.candidaturas(candidato_auth_user_id,aplicada_em desc);
create index candidaturas_vaga_status_idx on public.candidaturas(vaga_id,status);
create index candidaturas_habilidades_idx on public.candidaturas using gin(habilidades);
create index candidaturas_areas_idx on public.candidaturas using gin(areas);

create table public.feedbacks (
  id bigint generated by default as identity primary key,
  candidatura_id bigint not null references public.candidaturas(id),
  etapa text,
  template_nome text,
  assunto text,
  remetente text,
  canal text not null default 'manual' check (canal in ('manual','externo','email')),
  status text not null check (status in ('pendente','enviado','agendado','nao_necessario','falhou')),
  observacao text,
  responsavel_auth_user_id uuid not null references auth.users(id),
  agendado_em timestamptz,
  enviado_em timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index feedbacks_candidatura_created_idx on public.feedbacks(candidatura_id,created_at desc,id desc);

alter table public.empresas enable row level security;
alter table public.vagas enable row level security;
alter table public.candidaturas enable row level security;
alter table public.feedbacks enable row level security;

revoke all on public.empresas, public.vagas, public.candidaturas, public.feedbacks from anon, authenticated;
grant select on public.empresas to anon, authenticated;
grant insert, update on public.empresas to authenticated;
grant select on public.vagas to anon, authenticated;
grant insert, update on public.vagas to authenticated;
grant select, insert on public.candidaturas to authenticated;
grant update(status,etapa_atual,updated_at) on public.candidaturas to authenticated;
grant select, insert on public.feedbacks to authenticated;
grant usage,select on sequence public.empresas_id_seq, public.vagas_id_seq, public.candidaturas_id_seq, public.feedbacks_id_seq to authenticated;

create policy empresas_publicas on public.empresas for select to anon,authenticated
  using (ativa and exists (
    select 1 from public.vagas v where v.empresa_id=empresas.id and v.status='ativa' and v.visibilidade='publica'
  ));
create policy empresas_colaborador_ler on public.empresas for select to authenticated
  using (ativa and (select auth.jwt()->'app_metadata'->>'role')='colaborador');
create policy empresas_comercial_ler on public.empresas for select to authenticated
  using ((select auth.jwt()->'app_metadata'->>'role')='comercial');
create policy empresas_comercial_inserir on public.empresas for insert to authenticated
  with check ((select auth.jwt()->'app_metadata'->>'role')='comercial' and cadastrada_por=(select auth.uid()));
create policy empresas_comercial_atualizar on public.empresas for update to authenticated
  using ((select auth.jwt()->'app_metadata'->>'role')='comercial')
  with check ((select auth.jwt()->'app_metadata'->>'role')='comercial');

create policy vagas_publicas on public.vagas for select to anon,authenticated
  using (status='ativa' and visibilidade='publica' and (select auth.jwt()->'app_metadata'->>'role') is distinct from 'colaborador');
create policy vagas_responsavel_ler on public.vagas for select to authenticated
  using (responsavel_auth_user_id=(select auth.uid()) and (select auth.jwt()->'app_metadata'->>'role')='colaborador');
create policy vagas_responsavel_inserir on public.vagas for insert to authenticated
  with check (responsavel_auth_user_id=(select auth.uid()) and (select auth.jwt()->'app_metadata'->>'role')='colaborador');
create policy vagas_responsavel_atualizar on public.vagas for update to authenticated
  using (responsavel_auth_user_id=(select auth.uid()) and (select auth.jwt()->'app_metadata'->>'role')='colaborador')
  with check (responsavel_auth_user_id=(select auth.uid()) and (select auth.jwt()->'app_metadata'->>'role')='colaborador');

create policy candidaturas_proprio_candidato_ler on public.candidaturas for select to authenticated
  using (candidato_auth_user_id=(select auth.uid()));
create policy candidaturas_responsavel_ler on public.candidaturas for select to authenticated
  using ((select auth.jwt()->'app_metadata'->>'role')='colaborador' and exists (
    select 1 from public.vagas v where v.id=vaga_id and v.responsavel_auth_user_id=(select auth.uid())
  ));
create policy candidaturas_candidato_inserir on public.candidaturas for insert to authenticated
  with check (
    candidato_auth_user_id=(select auth.uid())
    and (select auth.jwt()->'app_metadata'->>'role') is distinct from 'colaborador'
    and status='em_andamento'
    and etapa_atual='Triagem curricular'
    and exists (select 1 from public.usuarios u where u.id=usuario_id and u.auth_user_id=(select auth.uid())
      and u.email=email_candidato and u.nome=nome_candidato)
    and exists (select 1 from public.vagas v where v.id=vaga_id and v.status='ativa' and v.visibilidade='publica'
      and (v.inscricoes_inicio is null or v.inscricoes_inicio<=current_date)
      and (v.inscricoes_fim is null or v.inscricoes_fim>=current_date))
  );
create policy candidaturas_responsavel_atualizar on public.candidaturas for update to authenticated
  using ((select auth.jwt()->'app_metadata'->>'role')='colaborador' and exists (
    select 1 from public.vagas v where v.id=vaga_id and v.responsavel_auth_user_id=(select auth.uid())
  ))
  with check ((select auth.jwt()->'app_metadata'->>'role')='colaborador' and exists (
    select 1 from public.vagas v where v.id=vaga_id and v.responsavel_auth_user_id=(select auth.uid())
  ));

create policy feedbacks_responsavel_ler on public.feedbacks for select to authenticated
  using ((select auth.jwt()->'app_metadata'->>'role')='colaborador' and exists (
    select 1 from public.candidaturas ca join public.vagas v on v.id=ca.vaga_id
    where ca.id=candidatura_id and v.responsavel_auth_user_id=(select auth.uid())
  ));
create policy feedbacks_responsavel_inserir on public.feedbacks for insert to authenticated
  with check (responsavel_auth_user_id=(select auth.uid()) and (select auth.jwt()->'app_metadata'->>'role')='colaborador' and exists (
    select 1 from public.candidaturas ca join public.vagas v on v.id=ca.vaga_id
    where ca.id=candidatura_id and v.responsavel_auth_user_id=(select auth.uid())
  ));
